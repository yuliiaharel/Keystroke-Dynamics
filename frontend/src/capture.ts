/**
 * Records raw key-timing events for one typing sample.
 *
 * Deliberately records only `event.code` (which physical key), the
 * action (down/up), and a timestamp relative to the first event in the
 * sample -- never `event.key` or any textarea value, so the typed text
 * itself is never captured, let alone sent.
 */

export type KeyAction = "down" | "up";

export interface CapturedEvent {
  code: string;
  action: KeyAction;
  t_ms: number;
}

function actionFor(type: string): KeyAction | null {
  if (type === "keydown") return "down";
  if (type === "keyup") return "up";
  return null;
}

export class KeystrokeCapture {
  private events: CapturedEvent[] = [];
  private firstTimestamp: number | null = null;
  private readonly listener = (event: KeyboardEvent): void => {
    this.record(event);
  };

  /** Starts recording keydown/keyup events on `target`. */
  attach(target: EventTarget): void {
    target.addEventListener("keydown", this.listener as EventListener);
    target.addEventListener("keyup", this.listener as EventListener);
  }

  detach(target: EventTarget): void {
    target.removeEventListener("keydown", this.listener as EventListener);
    target.removeEventListener("keyup", this.listener as EventListener);
  }

  record(event: KeyboardEvent): void {
    // Repeated keydowns (holding a key) and anything not generated by
    // the browser's own input handling are not genuine typing signal.
    if (event.repeat || !event.isTrusted) return;

    const action = actionFor(event.type);
    if (action === null) return;

    if (this.firstTimestamp === null) {
      this.firstTimestamp = event.timeStamp;
    }

    this.events.push({
      code: event.code,
      action,
      t_ms: event.timeStamp - this.firstTimestamp,
    });
  }

  /** Number of events recorded so far. */
  get count(): number {
    return this.events.length;
  }

  /**
   * Returns the recorded sample as a fresh array of fresh objects.
   * Deliberately never mutates `this.events` -- the original app's
   * `timelog` array was normalized in place on send, so calling its
   * submit handler a second time (e.g. a retried request) corrupted
   * the data it had already converted. Calling this twice must always
   * produce the same values.
   */
  sample(): CapturedEvent[] {
    return this.events.map((event) => ({ ...event }));
  }

  reset(): void {
    this.events = [];
    this.firstTimestamp = null;
  }
}
